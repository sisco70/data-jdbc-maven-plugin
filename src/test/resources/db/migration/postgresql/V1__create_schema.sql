CREATE TABLE table_two
(
    id        int8 GENERATED BY DEFAULT AS IDENTITY                                  NOT NULL,
    code      int4                                                                   NULL,
    json_data jsonb                                                                  NULL,
    json_txt  json                                                                   NULL,
    date_end  timestamptz DEFAULT '9999-12-31 01:00:00+01'::timestamp with time zone NOT NULL,
    CONSTRAINT table_two_pk PRIMARY KEY (id)
);

COMMENT ON TABLE table_two IS 'Main entity table storing dynamic payload details and record validity timelines.';
COMMENT ON COLUMN table_two.id IS 'Auto-generated 64-bit primary key identifier.';
COMMENT ON COLUMN table_two.code IS 'Optional numeric status or external system mapping code.';
COMMENT ON COLUMN table_two.json_data IS 'Flexible dynamic metadata payload stored in binary JSONB format.';
COMMENT ON COLUMN table_two.json_txt IS 'Unparsed plain-text JSON payload stored in standard JSON format.';
COMMENT ON COLUMN table_two.date_end IS 'Validity end timestamp. Defaults to far-future timestamp for active records.';


CREATE TABLE table_three
(
    id           uuid DEFAULT gen_random_uuid() NOT NULL,
    id_table_two int8                           NOT NULL,
    id_table_one int2                           NOT NULL,
    time_one     time                           NOT NULL,
    date_one     date                           NOT NULL,
    instant_one  timestamp                      NOT NULL,
    instant_tz   timestamptz                    NOT NULL,
    doc          bytea                          NULL,
    CONSTRAINT table_three_pk PRIMARY KEY (id),
    CONSTRAINT table_three_table_two_fk FOREIGN KEY (id_table_two) REFERENCES table_two (id),
    CONSTRAINT table_three_table_one_fk FOREIGN KEY (id_table_one) REFERENCES table_one (id)
);

COMMENT ON TABLE table_three IS 'Transactional log and attachment table linking primary entities to event instances.';
COMMENT ON COLUMN table_three.id IS 'Unique UUID primary key generated automatically.';
COMMENT ON COLUMN table_three.id_table_two IS 'Foreign key reference to the parent record in table_two.';
COMMENT ON COLUMN table_three.id_table_one IS 'Foreign key reference to the associated type in table_one.';
COMMENT ON COLUMN table_three.time_one IS 'Execution time component without time zone information.';
COMMENT ON COLUMN table_three.date_one IS 'Calendar date without time component.';
COMMENT ON COLUMN table_three.instant_one IS 'Local timestamp without time zone information.';
COMMENT ON COLUMN table_three.instant_tz IS 'Exact event timestamp with time zone awareness.';
COMMENT ON COLUMN table_three.doc IS 'Binary raw data content or attached file payload.';


